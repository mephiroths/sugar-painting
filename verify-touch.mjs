import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {launchBrowser,studioControl} from './browser-test.mjs';
const root=path.dirname(fileURLToPath(import.meta.url)),browser=await launchBrowser();
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1,reducedMotion:'reduce'});
const page=await context.newPage(),cdp=await context.newCDPSession(page),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const state=()=>page.evaluate(()=>sugarStudio.getState());
const touch=(type,touchPoints)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints});
const point=(id,p)=>({id,x:p.x,y:p.y,radiusX:5,radiusY:5,force:1});
try {
  await page.goto(pathToFileURL(path.join(root,'糖画铺.html')).href+'?mode=template');await page.waitForFunction(()=>window.sugarStudio);
  assert.equal(await page.locator('#scene-undo').isVisible(),true);
  assert.equal(await page.locator('#scene-undo').isDisabled(),true);
  assert.equal(await page.locator('#scene-finish').isDisabled(),true);
  await page.evaluate(()=>{window.pointerLog=[];for(const name of ['pointerdown','pointerup','pointercancel','lostpointercapture'])document.addEventListener(name,e=>pointerLog.push([name,e.pointerId,e.isPrimary,e.target.id]),true);});
  await page.locator('#scene').scrollIntoViewIfNeeded();
  const [a,b,c]=await page.evaluate(()=>[[-1,0],[1,0],[0,1]].map(([x,z])=>sugarStudio.projectPoint(x,z)));
  await touch('touchStart',[point(0,a)]);await page.waitForTimeout(250);assert.equal((await state()).drawing,true);
  await touch('touchStart',[point(0,a),point(1,c)]);
  await touch('touchMove',[point(0,a),point(1,b)]);await page.waitForTimeout(200);
  assert.ok((await state()).pour.source[0]<-.8,'a second finger must not steer the spoon');
  await touch('touchEnd',[point(1,b)]);
  assert.equal((await state()).drawing,true,`lifting a second finger must not end the first stroke: ${JSON.stringify(await page.evaluate(()=>pointerLog))}`);
  await touch('touchMove',[point(0,b)]);await page.waitForTimeout(300);await touch('touchEnd',[]);
  await page.waitForFunction(()=>!sugarStudio.getState().drawing&&!sugarStudio.getState().draining&&sugarStudio.getState().strokes===1);
  assert.ok((await state()).material.volume>0);
  const beforeUndo=await state(),scrollY=await page.evaluate(()=>window.scrollY);
  await page.locator('#scene-undo').click();assert.equal((await state()).strokes,0);assert.equal(await page.locator('#scene-redo').isDisabled(),false);
  await page.locator('#scene-redo').click();assert.equal((await state()).strokes,1);assert.ok(Math.abs((await state()).material.volume-beforeUndo.material.volume)<beforeUndo.material.volume*1e-5);
  assert.equal(await page.evaluate(()=>window.scrollY),scrollY,'quick controls do not move the page');
  await page.screenshot({path:path.join(root,'artifacts','mobile-quick-controls.png')});
  await page.setViewportSize({width:844,height:390});await page.locator('#scene').scrollIntoViewIfNeeded();
  const start=await page.evaluate(()=>sugarStudio.projectPoint(0,0));
  await touch('touchStart',[point(2,start)]);await page.waitForTimeout(350);await touch('touchCancel',[]);
  await page.waitForFunction(()=>!sugarStudio.getState().drawing&&!sugarStudio.getState().draining);
  assert.equal((await state()).strokes,2);
  await page.locator('#scene-finish').click();assert.equal((await state()).finished,true);assert.equal(await page.locator('#scene-undo').isVisible(),false);
  await page.locator('#resume-drawing').click();assert.equal(await page.locator('#scene-undo').isVisible(),true);
  await (await studioControl(page,'#focus-view')).click();assert.equal(await page.locator('#scene-undo').isVisible(),true);
  await (await studioControl(page,'#focus-view')).click();await page.locator('#watch-mode').click();assert.equal(await page.locator('#scene-undo').isVisible(),false);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,checks:['multi-touch ignores other fingers','release drains and commits','mobile quick undo and redo','quick finish and resume','focus and watch modes','cancel commits without a stuck stroke','orientation change'],errors},null,2));
} finally {await context.close();await browser.close();}
