import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {launchBrowser,studioControl} from './browser-test.mjs';
const root=path.dirname(fileURLToPath(import.meta.url));
const browser=await launchBrowser();
const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(pathToFileURL(path.join(root,'糖画铺.html')).href+'?mode=template');
  await page.waitForFunction(()=>window.sugarStudio);
  await (await studioControl(page,'#step-guide')).check();
  await page.keyboard.press('Escape');
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).template.step,0);
  assert.match(await page.locator('#step-label').textContent(),/第 1 \/ 28 笔/);
  assert.equal(await page.locator('#step-prev').isDisabled(),true);
  await page.screenshot({path:path.join(root,'artifacts','step-guide-mobile.png'),fullPage:true});
  await page.locator('#step-next').click();
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).template.step,1);
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).strokes,0);
  await page.locator('#draw-mode').click();assert.equal(await page.locator('#step-controls').isVisible(),false);
  await page.locator('#template-mode').click();assert.equal(await page.locator('#step-controls').isVisible(),true);
  await (await studioControl(page,'.pattern[data-index="2"]')).click();
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).template.step,0);
  assert.match(await page.locator('#step-label').textContent(),/第 1 \/ 14 笔/);
  await (await studioControl(page,'#template-visible')).uncheck();
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).template.visible,false);
  await (await studioControl(page,'#step-guide')).uncheck();await (await studioControl(page,'#step-guide')).check();
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).template.visible,true);
  await page.setViewportSize({width:1280,height:800});
  await page.screenshot({path:path.join(root,'artifacts','step-guide-desktop.png')});
  await (await studioControl(page,'#step-guide')).uncheck();
  assert.equal((await page.evaluate(()=>sugarStudio.getState())).template.step,null);
  await (await studioControl(page,'#step-guide')).check();await page.keyboard.press('Escape');
  await page.locator('#watch-mode').click();assert.equal(await page.locator('#step-controls').isVisible(),false);
  await page.locator('#template-mode').click();assert.equal(await page.locator('#step-controls').isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,checks:['step navigation','pattern resets step','guide visibility','mobile and desktop rendering'],errors},null,2));
} finally {await browser.close();}
